const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.goto('http://127.0.0.1:4173');
  await page.waitForTimeout(2000);
  await page.evaluate(() => window.scrollTo(0, 900));
  await page.waitForTimeout(500);
  const cards = page.locator('.brutal-card');
  const count = await cards.count();
  console.log('cards', count);
  const a = cards.nth(0);
  const b = cards.nth(1);
  const boxA = await a.boundingBox();
  const boxB = await b.boundingBox();
  console.log('A', boxA.x, boxA.y, 'B', boxB.x, boxB.y);
  await page.mouse.move(boxA.x+10, boxA.y+10);
  await page.mouse.down();
  await page.mouse.move(boxB.x+10, boxB.y+10, { steps: 20 });
  await page.mouse.up();
  await page.waitForTimeout(1000);
  const newA = await cards.nth(0).boundingBox();
  const newB = await cards.nth(1).boundingBox();
  console.log('after first', newA.x, newA.y, 'second', newB.x, newB.y);
  await browser.close();
})();
